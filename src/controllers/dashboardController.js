import { Expense } from '../models/Expense.js'
import dashboardData from '../data/dashboard.json' with { type: 'json' }

export async function getDashboard(req, res) {
  const useMockData = process.env.USE_MOCK_DATA === 'true'

  // if (useMockData) {
  //   return res.json(dashboardData)
  // }

  try {
    // Fetch expenses (for now, all expenses; later we can limit by date/user)
    const expenses = await Expense.find({}).sort({ date: -1 })

    if (!expenses.length) {
      return res.json({
        greeting: {
          title: 'Welcome 👋',
          description: 'No expenses recorded yet. Add some expenses to see your dashboard.',
        },
        summaryCards: [],
        trend: { label: '₹0', bars: [] },
        categoryBreakdown: { total: 0, items: [] },
        aiInsight: {
          title: 'No insights yet',
          subtitle: 'Add expenses to generate insights',
          description: 'Once you start adding expenses, AI will generate spending insights.',
        },
        recentTransactions: [],
      })
    }

    // Total expenses
    const totalExpenses = expenses.reduce((sum, exp) => sum + exp.amount, 0)

    // Category totals
    const categoryTotals = {}
    for (const exp of expenses) {
      categoryTotals[exp.category] = (categoryTotals[exp.category] || 0) + exp.amount
    }

    // Top category
    const [topCategoryName, topCategoryAmount] = Object.entries(categoryTotals).sort(
      (a, b) => b[1] - a[1],
    )[0] || ['N/A', 0]

    // Summary cards (similar structure to original JSON)
    const summaryCards = [
      {
        id: 'total-expenses',
        title: 'Total Expenses',
        value: `₹${totalExpenses.toFixed(2)}`,
        change: 'Based on all recorded expenses',
        icon: 'wallet',
      },
      {
        id: 'monthly-budget',
        title: 'Monthly Budget',
        value: '₹65,000',
        change: 'Sample remaining budget',
        icon: 'savings',
      },
      {
        id: 'top-category',
        title: 'Top Category',
        value: topCategoryName,
        change: `₹${topCategoryAmount.toFixed(2)} spent`,
        icon: 'trendingDown',
      },
      {
        id: 'potential-savings',
        title: 'Potential Savings',
        value: '₹4,500',
        change: 'Identified by AI (sample)',
        icon: 'autoGraph',
      },
    ]

    // Trend: simple example using total expenses; can be made more sophisticated
    const trend = {
      label: `₹${totalExpenses.toFixed(2)}`,
      bars: [35, 52, 48, 72, 68, 88],
    }

    // Category breakdown items with colors
    const colors = ['#4c6fff', '#7b61ff', '#22c55e', '#f59e0b', '#e879f9']
    const categoryBreakdownItems = Object.keys(categoryTotals).map((category, index) => ({
      label: category,
      color: colors[index % colors.length],
    }))

    const categoryBreakdown = {
      total: expenses.length,
      items: categoryBreakdownItems,
    }

    const aiInsight = {
      title: 'AI Spending Insight',
      subtitle: 'Generated recommendation',
      description:
        'Based on your current expenses, consider reviewing your top spending categories to identify potential savings.',
    }

    const recentTransactions = expenses.slice(0, 3).map((exp) => ({
      id: exp._id.toString(),
      merchant: exp.merchant,
      category: exp.category,
      amount: `-₹${exp.amount.toFixed(2)}`,
      time: exp.date.toLocaleString('en-IN'),
    }))

    const greeting = {
      title: 'Good morning, Riya 👋',
      description:
        'Here is an overview of your spending and the latest insights generated by your AI expense assistant.',
    }

    res.json({
      greeting,
      summaryCards,
      trend,
      categoryBreakdown,
      aiInsight,
      recentTransactions,
    })
  } catch (error) {
    console.error('Error building dashboard from DB:', error)
    res.status(500).json({ message: 'Failed to load dashboard data' })
  }
}
