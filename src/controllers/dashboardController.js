import { Expense } from '../models/Expense.js'
import { UserProfile } from '../models/UserProfile.js'
import { getSpendingSummaryInsight } from '../services/ai/insightService.js'

export async function getDashboard(req, res) {
  try {
    const userId = req.query.userId || 'riya-demo'

    // Fetch user profile (for budget and personalization)
    let profile = await UserProfile.findOne({ userId }).lean()

    if (!profile) {
      profile = await UserProfile.create({
        userId,
        name: 'Riya',
        email: 'riya@example.com',
        monthlyBudget: 65000,
        currency: 'INR',
      })
    }

    // Fetch expenses for this user
    const expenses = await Expense.find({ userId }).sort({ date: -1 })

    if (!expenses.length) {
      return res.json({
        greeting: {
          title: 'Welcome 👋',
          description: 'No expenses recorded yet. Add some expenses to see your dashboard.',
        },
        summaryCards: [],
        trend: { label: '₹0', bars: [] },
        categoryBreakdown: { total: 0, items: [] },
        aiInsight: {
          title: 'No insights yet',
          subtitle: 'Add expenses to generate insights',
          description: 'Once you start adding expenses, AI will generate spending insights.',
        },
        recentTransactions: [],
      })
    }

    // Total expenses for this user
    const totalExpenses = expenses.reduce((sum, exp) => sum + exp.amount, 0)

    // Category totals
    const categoryTotals = {}
    for (const exp of expenses) {
      categoryTotals[exp.category] = (categoryTotals[exp.category] || 0) + exp.amount
    }

    // Top category
    const [topCategoryName, topCategoryAmount] = Object.entries(categoryTotals).sort(
      (a, b) => b[1] - a[1],
    )[0] || ['N/A', 0]

    const remainingBudget = Math.max(profile.monthlyBudget - totalExpenses, 0)

    // Summary cards (all values derived from DB/UserProfile)
    const summaryCards = [
      {
        id: 'total-expenses',
        title: 'Total Expenses',
        value: `₹${totalExpenses.toFixed(2)}`,
        change: 'Based on all recorded expenses',
        icon: 'wallet',
      },
      {
        id: 'monthly-budget',
        title: 'Monthly Budget',
        value: `₹${profile.monthlyBudget.toFixed(2)}`,
        change: `₹${remainingBudget.toFixed(2)} remaining`,
        icon: 'savings',
      },
      {
        id: 'top-category',
        title: 'Top Category',
        value: topCategoryName,
        change: `₹${topCategoryAmount.toFixed(2)} spent`,
        icon: 'trendingDown',
      },
      {
        id: 'potential-savings',
        title: 'Potential Savings',
        value: '₹0',
        change: 'Calculated by AI insights',
        icon: 'autoGraph',
      },
    ]

    // Trend: total per day for the last 6 days
    const daysCount = 6
    const dailyTotals = new Array(daysCount).fill(0)
    const now = new Date()

    for (const exp of expenses) {
      const diffMs = now - exp.date
      const diffDays = Math.floor(diffMs / (24 * 60 * 60 * 1000))

      if (diffDays >= 0 && diffDays < daysCount) {
        const index = daysCount - 1 - diffDays
        dailyTotals[index] += exp.amount
      }
    }

    const maxDailyTotal = Math.max(...dailyTotals, 1)
    const bars = dailyTotals.map((total) => Math.round((total / maxDailyTotal) * 100))

    const trend = {
      label: `₹${totalExpenses.toFixed(2)}`,
      bars,
    }

    // Category breakdown items with colors
    const colors = ['#4c6fff', '#7b61ff', '#22c55e', '#f59e0b', '#e879f9']
    const categoryBreakdownItems = Object.keys(categoryTotals).map((category, index) => ({
      label: category,
      color: colors[index % colors.length],
    }))

    const categoryBreakdown = {
      total: expenses.length,
      items: categoryBreakdownItems,
    }

    // AI insight: use AI service to generate a data-driven spending summary insight
    const summaryInsight = await getSpendingSummaryInsight(userId)

    const aiInsight = {
      title: summaryInsight.title,
      subtitle: 'AI-generated spending insight',
      description: summaryInsight.summary,
      severity: summaryInsight.severity,
    }

    const recentTransactions = expenses.slice(0, 3).map((exp) => ({
      id: exp._id.toString(),
      merchant: exp.merchant,
      category: exp.category,
      amount: `-₹${exp.amount.toFixed(2)}`,
      time: exp.date.toLocaleString('en-IN'),
    }))

    const greeting = {
      title: 'Good morning, Riya 👋',
      description:
        'Here is an overview of your spending and the latest insights generated by your AI expense assistant.',
    }

    res.json({
      greeting,
      summaryCards,
      trend,
      categoryBreakdown,
      aiInsight,
      recentTransactions,
    })
  } catch (error) {
    console.error('Error building dashboard from DB:', error)
    res.status(500).json({ message: 'Failed to load dashboard data' })
  }
}
